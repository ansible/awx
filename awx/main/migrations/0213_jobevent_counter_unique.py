def dedup_jobevent(apps, schema_editor):
    """Remove duplicate (job_id, counter, job_created) rows before adding the unique
    constraint. Duplicates can exist when two controllers concurrently streamed the same
    receptor work unit (slow-controller adoption race). We keep the row with the lowest
    primary key (earliest insert) and delete the rest.

    In practice this is almost always a no-op: the ownership-polling fix in
    _await_processor (AAP-96718) reduces the concurrent-stream window to ~1 event,
    so production tables will rarely carry duplicates.

    NOTE: On large production deployments this table is partitioned. Run
    CREATE UNIQUE INDEX CONCURRENTLY per partition before applying this migration to
    avoid a full-table lock, then use ALTER TABLE ... ADD CONSTRAINT ... USING INDEX.
    """
    with schema_editor.connection.cursor() as cursor:
        cursor.execute(
            """
            DELETE FROM main_jobevent a
            USING main_jobevent b
            WHERE a.id > b.id
              AND a.job_id = b.job_id
              AND a.counter = b.counter
              AND a.job_created = b.job_created
            """
        )


